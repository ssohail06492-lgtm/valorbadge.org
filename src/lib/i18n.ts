/**
 * Intelligent translate function that resolves by key name or common UI text.
 * Completely updates the app across Tamil, Hindi, English, and other supported languages.
 */
export function translate(keyOrText: string, lang: SupportedLanguage = 'en'): string {
  if (!keyOrText || typeof keyOrText !== 'string') return '';
  const trimmed = keyOrText.trim();
  if (!trimmed) return keyOrText;

  const dict = getTranslation(lang);

  // 1. Direct dictionary key match
  if (trimmed in dict && dict[trimmed]) {
    return dict[trimmed];
  }

  const normalized = trimmed.toLowerCase();

  // 2. Direct phrase lookup in phrase table for requested language (Tamil, Hindi, etc.)
  const phraseTable = PHRASE_TRANSLATIONS[lang];
  if (phraseTable && phraseTable[normalized]) {
    return phraseTable[normalized];
  }

  // 3. Lookup canonical English phrase in COMMON_PHRASES_TO_KEY
  const matchedKey = COMMON_PHRASES_TO_KEY[normalized];
  if (matchedKey && dict[matchedKey]) {
    return dict[matchedKey];
  }

  // 4. If English requested, return from en dict or as-is
  if (lang === 'en') {
    if (matchedKey && translations.en[matchedKey]) {
      return translations.en[matchedKey];
    }
    return keyOrText;
  }

  // 5. Fallback to English dictionary if key exists in en
  const enDict = translations.en;
  if (trimmed in enDict) {
    return enDict[trimmed];
  }

  // 6. Return as-is (e.g. for user data or untouched content)
  return keyOrText;
}
